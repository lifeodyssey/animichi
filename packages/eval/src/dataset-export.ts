import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { FROZEN_DATASET_COUNTS, frozenDataset, type FrozenDatasetCount } from './dataset-sets.ts';
import { EVALUATOR_NAMES } from './evaluator-names.ts';
import { canonicalDatasetPath } from './gate/case-strata.ts';
import { objectOrNull } from './json-object.ts';

/**
 * The regeneration path for the six exported dataset fixtures (#1746).
 *
 * `fixtures/<set>.json` is a **pure function of two committed inputs**: the
 * canonical corpus Python wrote (`datasets/canonical/<set>.json`, frozen in
 * #1603) and the evaluator roster `src/evaluator-names.ts` declares the export
 * is allowed to contain. This module is that function. #1603 removed the Python
 * exporter and left the fixtures as bytes nothing in the tree could reproduce —
 * which is what made the `logfire`/`pydantic-evals` pin in `PINS.json`
 * unmovable. It is now movable: `pnpm run eval:regenerate-fixtures` re-emits
 * every fixture and `test/dataset-export.test.ts` holds the committed bytes to
 * the derivation, so a fixture edited without its input (or the reverse) is a
 * red test rather than a silent divergence.
 *
 * The mapping is the one pydantic-evals' `Dataset.to_file` performed, and it is
 * lossless ONLY in the direction it ran: `path`, `tier`, the canonical
 * `metadata` block and `expected_tools` do not survive the export, and the
 * regenerated bytes intentionally do not carry them either. Reproducing the
 * committed export is the whole job here; changing what the export keeps is an
 * Eval Story.
 *
 * What this module deliberately does NOT re-derive: `fixtures/stats-oracle.json`
 * and `fixtures/evaluator-oracle.json`. Those are Python's own answers, written
 * by `stats_oracle.py` and `evaluator_oracle.py` running `stats.py`/`gate.py`,
 * and their producer retired with the Python agent. Re-deriving them from the TS
 * ports that the parity tests measure against them would turn every one of those
 * tests into a tautology, so they stay frozen witnesses under a deliberate-edit
 * rule (#1463) and nothing here reads or writes them.
 */

/** One exported case, in the shape `Dataset.to_file` wrote it. */
interface ExportedCase {
  name: string;
  inputs: Readonly<Record<string, unknown>>;
  metadata: Readonly<Record<string, unknown>>;
  expected_output: null;
  evaluators: readonly never[];
}

/** One exported dataset fixture document — the committed `fixtures/<set>.json`. */
export interface ExportedDataset {
  name: string;
  cases: readonly ExportedCase[];
  evaluators: readonly string[];
  report_evaluators: readonly never[];
}

/** A committed export the derivation no longer reproduces. */
export interface FixtureDrift {
  readonly set: string;
  readonly committed: string;
  readonly derived: string;
}

/** What a `--write` run re-emitted, and which of the six actually moved. */
export interface RegeneratedFixtures {
  readonly total: number;
  readonly moved: readonly string[];
}

const FIXTURES_DIR = fileURLToPath(new URL('../fixtures/', import.meta.url));

/** The set names `fixtures/` carries an export for, in the frozen declaration's order. */
export function exportedSetNames(): readonly string[] {
  return FROZEN_DATASET_COUNTS.map((set) => set.name);
}

/** Where a set's committed export lives. */
export function fixturePath(setName: string): string {
  return `${FIXTURES_DIR}${setName}.json`;
}

/** The document `fixtures/<set>.json` must carry, re-derived from its two inputs. */
export function exportedDatasetDocument(setName: string): ExportedDataset {
  const frozen = frozenDataset(setName);
  return {
    name: frozen.name,
    cases: exportedCases(frozen),
    evaluators: [...EVALUATOR_NAMES],
    report_evaluators: [],
  };
}

/** The bytes `fixtures/<set>.json` must carry: two-space indent, UTF-8 unescaped, one trailing newline. */
export function exportedDatasetText(setName: string): string {
  return `${JSON.stringify(exportedDatasetDocument(setName), null, 2)}\n`;
}

/** Every committed export the derivation no longer reproduces, in set order. */
export function fixtureDrifts(): readonly FixtureDrift[] {
  return exportedSetNames().map((setName) => fixtureDrift(setName)).filter(isDrift);
}

/**
 * One committed export against its derivation, or `null` when they agree.
 *
 * The path is overridable so the drift gate can be shown to go red — a
 * comparison that has only ever been seen to pass is not a gate. Production
 * callers never pass one; the committed location is `fixturePath(setName)`.
 */
export function fixtureDrift(setName: string, committedPath = fixturePath(setName)): FixtureDrift | null {
  const derived = exportedDatasetText(setName);
  const committed = readFileSync(committedPath, 'utf8');
  return committed === derived ? null : { set: setName, committed, derived };
}

/** Re-emit every committed export from the derivation, and name the ones whose bytes moved. */
export function regenerateFixtures(): RegeneratedFixtures {
  const names = exportedSetNames();
  return { total: names.length, moved: names.filter(writeFixture) };
}

function isDrift(drift: FixtureDrift | null): drift is FixtureDrift {
  return drift !== null;
}

/** Write the derived bytes over the committed export; whether that changed them. */
function writeFixture(setName: string): boolean {
  const derived = exportedDatasetText(setName);
  const moved = readFileSync(fixturePath(setName), 'utf8') !== derived;
  writeFileSync(fixturePath(setName), derived, 'utf8');
  return moved;
}

function exportedCases(frozen: FrozenDatasetCount): readonly ExportedCase[] {
  return canonicalRows(frozen).map((row, index) =>
    exportedCase(row, `${frozen.name} canonical row ${String(index)}`));
}

/** The canonical rows, held to the count the frozen declaration pins. */
function canonicalRows(frozen: FrozenDatasetCount): readonly Readonly<Record<string, unknown>>[] {
  const parsed: unknown = JSON.parse(readFileSync(canonicalDatasetPath(frozen.name), 'utf8'));
  if (!Array.isArray(parsed)) throw new TypeError(`${frozen.name}: a canonical dataset must be a list of rows`);
  if (parsed.length !== frozen.caseCount) throw new RangeError(countFinding(frozen, parsed.length));
  return parsed.map((row, index) => rowObject(row, frozen.name, index));
}

function countFinding(frozen: FrozenDatasetCount, found: number): string {
  return `${frozen.name}: the frozen export is ${String(frozen.caseCount)} cases, `
    + `the canonical set is ${String(found)} — refresh the frozen count or the export`;
}

function rowObject(row: unknown, setName: string, index: number): Readonly<Record<string, unknown>> {
  const record = objectOrNull(row);
  if (record === null) throw new TypeError(`${setName}: canonical row ${String(index)} is not an object`);
  return record;
}

function exportedCase(row: Readonly<Record<string, unknown>>, where: string): ExportedCase {
  return {
    name: rowText(row, 'id', where),
    inputs: exportedInputs(row),
    metadata: exportedMetadata(row, where),
    expected_output: null,
    evaluators: [],
  };
}

/**
 * The export's input block. `query` is optional in the canonical rows, and the
 * export wrote an empty prompt where a set carried none — `injection_g1_v1`
 * names its trigger `untrusted_content` instead — so the mapping reproduces that
 * rather than inventing a prompt. Whether that set should carry one is an Eval
 * Story, not a generator detail.
 */
function exportedInputs(row: Readonly<Record<string, unknown>>): Readonly<Record<string, unknown>> {
  return {
    query: row.query ?? '',
    locale: row.locale,
    context: row.context ?? null,
    selected_point_ids: row.selected_point_ids ?? null,
    selected_candidate_ids: row.selected_candidate_ids ?? null,
    clarification_id: row.clarification_id ?? null,
    seeded_pending: row.seeded_pending ?? null,
  };
}

/** The export's metadata block: the two stage/key lists and the non-empty flag, under Python's names. */
function exportedMetadata(row: Readonly<Record<string, unknown>>, where: string): Readonly<Record<string, unknown>> {
  return {
    acceptable_stages: stringList(row, 'acceptable_stages', where),
    data_keys: stringList(row, 'expected_data_keys', where),
    expect_nonempty: row.expect_nonempty ?? false,
  };
}

/** A declared string list, or the empty list a canonical row leaves absent. */
function stringList(row: Readonly<Record<string, unknown>>, key: string, where: string): readonly string[] {
  const value = row[key] ?? [];
  if (!isStringList(value)) throw new TypeError(`${where}: "${key}" must be a list of strings`);
  return value;
}

function isStringList(value: unknown): value is readonly string[] {
  return Array.isArray(value) && value.every((entry) => typeof entry === 'string');
}

function rowText(row: Readonly<Record<string, unknown>>, key: string, where: string): string {
  const value = row[key];
  if (typeof value !== 'string' || value === '') {
    throw new TypeError(`${where}: "${key}" must be a non-empty string`);
  }
  return value;
}
