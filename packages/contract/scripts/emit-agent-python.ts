/**
 * Emit the Agent boundary Python models from packages/contract/src/agent-contract.ts.
 *
 * Deterministic: schema key order drives output order; a second run produces
 * byte-identical output (enforced by the drift gate and agent-boundary.test.ts).
 * Supported: string / boolean / number / integer / nested object / array of
 * supported types / single-const or enum literals / nullability (a union with
 * exactly one non-null branch). Anything else — true unions, date-time
 * formats, arrays of unions — THROWS: an unsupported schema construct must
 * fail, never silently degrade.
 *
 * Output: apps/agent/src/animichi/interfaces/boundary/agent_models.py (committed).
 *
 * Run: pnpm emit:agent-python  (from packages/contract/)
 */

